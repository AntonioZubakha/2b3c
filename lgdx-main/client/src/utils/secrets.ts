// ==========================================================================
// DOCKER SECRETS UTILITY
// Утилита для чтения Docker secrets в браузере и Docker контейнере
// ==========================================================================

/**
 * Получает значение секрета из переменной окружения или файла
 * В клиентском (браузерном) бандле доступны только env-переменные на этапе сборки.
 *
 * ВАЖНО: Нельзя импортировать Node.js `fs` в CRA/webpack client build — даже через
 * динамический import и даже за `typeof window === 'undefined'`, потому что
 * бандлер всё равно пытается резолвить модуль и выдаёт warning "Can't resolve 'fs'".
 */
export const getSecretValue = async (envVar: string, filePath?: string): Promise<string> => {
  // filePath оставляем в сигнатуре для совместимости с существующими вызовами,
  // но в браузерном приложении он неприменим.
  void filePath;

  const value = process.env[envVar];
  return value || '';
};
